const FOCUS: Record<AnalysisKind, string> = {
  plot: '重点分析主线、关键转折、冲突与因果，以及人物选择如何改变局面；支线、家庭或社会处境若推动主线也应纳入。',
  characters: '重点分析人物目标、顾虑、认知与选择如何变化；区分自我认识、他人评价和实际行动，不把单次反应当成恒定性格。',
  relationships: '重点分析双方认知、立场、信任与相处方式的变化；区分单方面期待、相互确认和后续调整，说明外部关系如何影响选择。',
  style: '重点分析叙述人称与视角、用词与句式、段落节奏、对白比重和人物口吻，提炼在续写中可延续的写法。区分叙述者的语言和人物的语言。',
  custom: '围绕作者的具体问题组织结论与依据，保留回答该问题所需的前后文。',
}

export function analysisPrompt(stage: 'reading' | 'condense' | 'direct' | 'report' | 'final', kind: AnalysisKind): string {
  const base = `${PRINCIPLES}\n${FOCUS[kind]}`
  const style = kind === 'style'
  if (stage === 'reading') return `${base}\n${style ? STYLE_READING : READING}`
  if (stage === 'condense') return `${base}\n${style ? STYLE_CONDENSE : `${RECONCILE}\n${CONDENSE}`}`
  const form = style ? STYLE_FORM : `${RECONCILE}\n${FORM}`
  const tools = stage === 'direct'
    ? '全部所选正文已附在本次请求中，请直接对照正文核实。'
    : stage === 'final'
      ? '回查已经结束。全部阅读记录及本轮取得的原文材料已附上；直接据此完成报告，不再请求工具。已经取得的原文优先于阅读记录。对缺乏证据、确实影响结论的问题保留不确定性。'
      : (style ? STYLE_REREAD : REREAD)
  return `${base}\n${form}\n${tools}`
}

/** Model inputs expose only readable provenance, never database identities or offsets. */
export function analysisSourceMaterial({ id, chapterTitle, part, text }: AnalysisSource) {
  return { id, chapterTitle, part, text }
}
