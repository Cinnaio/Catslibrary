import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { MemoryRouter } from 'react-router-dom'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { DEFAULT_SITE_BRANDING } from '@shared/site-settings'
import type { PasskeyAdminSettings, TurnstileSettings } from '@shared/site-settings'

const mock = vi.hoisted(() => ({
  branding: vi.fn(), turnstile: vi.fn(), passkey: vi.fn(), saveBranding: vi.fn(), saveTurnstile: vi.fn(), savePasskey: vi.fn(),
  upload: vi.fn(), resetAsset: vi.fn(), testTurnstile: vi.fn(), refreshPolicy: vi.fn(), toast: vi.fn(), confirm: vi.fn(),
  contentPolicySettings: vi.fn(), mailSettings: vi.fn(),
}))
vi.mock('@/lib/api', () => ({ siteSettingsApi: mock, authApi: mock, adminApi: { contentPolicy: { settings: mock.contentPolicySettings } }, url: (path: string) => `/api${path}` }))
vi.mock('@/context/ContentPolicyContext', () => ({ useContentPolicy: () => ({ refreshPolicy: mock.refreshPolicy }) }))
vi.mock('@/components/feedback', () => ({ useToast: () => ({ toast: mock.toast }), useConfirm: () => ({ confirm: mock.confirm }) }))
vi.mock('@/components/TurnstileTestWidget', () => ({ default: ({ onToken }: { onToken: (token: string) => void }) => <button type="button" onClick={() => onToken('test-token')}>完成小组件</button> }))
import SiteSettingsTab from './SiteSettingsTab'

const settings: TurnstileSettings = { siteKey: 'public-key', hostnames: ['read.example.com'], secretSet: true, configured: true, encryptionReady: true, secretReadable: true, sources: { siteKey: 'database', secret: 'database', hostnames: 'database' } }
const passkeySettings: PasskeyAdminSettings = { enabled: false, registrationEnabled: true, rpName: 'Cat’s Library', rpId: 'localhost', origins: ['http://localhost:5173'], configured: true, userVerification: 'required', sources: { rpId: 'default', origins: 'default' } }
async function show(security = false) {
  render(<MemoryRouter initialEntries={[`/admin/site-settings?view=${security ? 'security' : 'branding'}`]}><SiteSettingsTab /></MemoryRouter>)
  await screen.findByRole('button', { name: '保存设置' })
}
beforeEach(() => {
  vi.resetAllMocks()
  mock.branding.mockResolvedValue({ ...DEFAULT_SITE_BRANDING })
  mock.turnstile.mockResolvedValue({ ...settings })
  mock.passkey.mockResolvedValue({ ...passkeySettings })
  mock.refreshPolicy.mockResolvedValue(undefined)
  mock.contentPolicySettings.mockResolvedValue({ adultContentEnabled: true, turnstileConfigured: true })
})
describe('SiteSettingsTab', () => {
  it('账号邮件按需读取，往返分区保留密码草稿并隐藏非当前分区保存条', async () => {
    mock.mailSettings.mockResolvedValue({ ready: true, mode: 'smtp', source: 'environment', revision: 0,
      host: 'smtp.example.test', port: 465, security: 'tls', username: 'user', passwordSet: true,
      from: 'account@example.test', publicOrigin: 'https://reader.example.test' })
    await show()
    expect(mock.mailSettings).not.toHaveBeenCalled()
    await userEvent.click(screen.getByRole('tab', { name: '账号邮件' }))
    await screen.findByLabelText('SMTP 服务器')
    fireEvent.change(screen.getByLabelText('SMTP 密码 / 授权码'), { target: { value: 'unsaved-password' } })
    expect(screen.getByRole('button', { name: '保存配置' })).toBeInTheDocument()
    await userEvent.click(screen.getByRole('tab', { name: '站点信息' }))
    expect(screen.queryByRole('button', { name: '保存配置' })).not.toBeInTheDocument()
    await userEvent.click(screen.getByRole('tab', { name: '账号邮件' }))
    expect(screen.getByLabelText('SMTP 密码 / 授权码')).toHaveValue('unsaved-password')
    expect(mock.mailSettings).toHaveBeenCalledTimes(1)
  })
  it('往返内容安全复用导航节点并保留键盘焦点与站点信息草稿', async () => {
    await show()
    fireEvent.change(screen.getByLabelText('站点名称'), { target: { value: '未保存名称' } })
    const navigation = screen.getByRole('tablist', { name: '站点设置视图切换' })
    const policyTab = screen.getByRole('tab', { name: '内容安全' })
    await userEvent.click(policyTab)
    await screen.findByRole('switch')
    expect(screen.getByRole('tablist', { name: '站点设置视图切换' })).toBe(navigation)
    expect(policyTab).toHaveFocus()
    await userEvent.keyboard('{ArrowLeft}')
    await userEvent.keyboard('{Enter}')
    await screen.findByLabelText('站点名称')
    expect(screen.getByRole('tablist', { name: '站点设置视图切换' })).toBe(navigation)
    expect(screen.getByRole('tab', { name: '站点信息' })).toHaveFocus()
    expect(screen.getByLabelText('站点名称')).toHaveValue('未保存名称')
    expect(mock.branding).toHaveBeenCalledTimes(1)
  })
  it('保存文字并更新预览；失败保留草稿', async () => {
    await show()
    const name = screen.getByLabelText('站点名称')
    expect(screen.getByRole('button', { name: '保存设置' })).toBeDisabled()
    fireEvent.change(name, { target: { value: '新书库' } })
    mock.saveBranding.mockRejectedValueOnce(new Error('网络失败'))
    fireEvent.click(screen.getByRole('button', { name: '保存设置' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('网络失败')
    expect(name).toHaveValue('新书库')
    mock.saveBranding.mockResolvedValueOnce({ ...DEFAULT_SITE_BRANDING, name: '新书库' })
    fireEvent.click(screen.getByRole('button', { name: '保存设置' }))
    await waitFor(() => expect(screen.getByRole('button', { name: '保存设置' })).toBeDisabled())
    expect(mock.saveBranding).toHaveBeenLastCalledWith(expect.objectContaining({ name: '新书库' }))
  })
  it('图片立即更新但保留未保存的文字', async () => {
    await show()
    fireEvent.change(screen.getByLabelText('站点名称'), { target: { value: '未保存名称' } })
    mock.upload.mockResolvedValue({ ...DEFAULT_SITE_BRANDING, logoUrl: '/api/site-settings/assets/logo?v=fixture' })
    fireEvent.change(screen.getByLabelText('Logo'), { target: { files: [new File(['image'], 'logo.png', { type: 'image/png' })] } })
    await waitFor(() => expect(mock.upload).toHaveBeenCalled())
    await waitFor(() => expect(screen.getByRole('button', { name: '保存设置' })).toBeEnabled())
    expect(screen.getByLabelText('站点名称')).toHaveValue('未保存名称')
    expect(mock.saveBranding).not.toHaveBeenCalled()
  })
  it('环境变量字段锁定，私钥不回显且未配置主密钥时不能输入', async () => {
    mock.turnstile.mockResolvedValue({ ...settings, encryptionReady: false, sources: { siteKey: 'environment', secret: 'environment', hostnames: 'environment' } })
    await show(true)
    expect(screen.getByLabelText('Site Key')).toBeDisabled()
    expect(screen.getByLabelText('Secret Key')).toBeDisabled()
    expect(screen.getByLabelText('Secret Key')).toHaveValue('')
    expect(screen.getByLabelText('允许验证的域名')).toBeDisabled()
  })
  it('私钥留空不替换，未保存修改禁止测试', async () => {
    mock.saveTurnstile.mockResolvedValue({ ...settings, hostnames: ['new.example.com'] })
    await show(true)
    fireEvent.change(screen.getByLabelText('允许验证的域名'), { target: { value: 'new.example.com' } })
    expect(screen.getByRole('button', { name: '开始 / 重新验证' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: '保存设置' }))
    await waitFor(() => expect(mock.saveTurnstile).toHaveBeenCalledWith({ siteKey: 'public-key', hostnames: ['new.example.com'], clearSecret: false }))
    await waitFor(() => expect(screen.getByRole('button', { name: '开始 / 重新验证' })).toBeEnabled())
    expect(mock.refreshPolicy).toHaveBeenCalled()
  })
  it('测试仅消费组件 token，完成后清空 token', async () => {
    mock.testTurnstile.mockResolvedValue({ ok: true, message: '通过，不授予访问权' })
    await show(true)
    fireEvent.click(screen.getByRole('button', { name: '开始 / 重新验证' }))
    expect(screen.getByRole('button', { name: '检查服务端验证' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: '完成小组件' }))
    fireEvent.click(screen.getByRole('button', { name: '检查服务端验证' }))
    expect(await screen.findByText('通过，不授予访问权')).toBeInTheDocument()
    expect(mock.testTurnstile).toHaveBeenCalledWith('test-token')
    expect(screen.getByRole('button', { name: '检查服务端验证' })).toBeDisabled()
  })
  it('Passkey 页面编辑开关与显示名称并保存，运行时边界只读', async () => {
    mock.passkey.mockResolvedValue({ ...passkeySettings, enabled: true })
    mock.savePasskey.mockResolvedValue({ ...passkeySettings, enabled: true, rpName: '书灯' })
    render(<MemoryRouter initialEntries={['/admin/site-settings?view=passkey']}><SiteSettingsTab /></MemoryRouter>)
    await screen.findByLabelText('Passkey 显示名称')
    expect(screen.getByText('localhost')).toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('Passkey 显示名称'), { target: { value: '书灯' } })
    fireEvent.click(screen.getByRole('switch', { name: /启用 Passkey 登录/ }))
    expect(screen.getByText('已保存状态：已开启 Passkey 登录。')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '保存设置' }))
    await waitFor(() => expect(mock.savePasskey).toHaveBeenCalledWith({ enabled: false, registrationEnabled: true, rpName: '书灯' }))
  })
  it('加载失败提供重试', async () => {
    mock.branding.mockRejectedValueOnce(new Error('读取失败'))
    render(<MemoryRouter><SiteSettingsTab /></MemoryRouter>)
    fireEvent.click(await screen.findByRole('button', { name: '重试' }))
    await screen.findByLabelText('站点名称')
  })
  it('配置按页读取，安全验证失败不阻塞 Passkey，重试不清除站点信息草稿', async () => {
    await show()
    expect(mock.turnstile).not.toHaveBeenCalled()
    expect(mock.passkey).not.toHaveBeenCalled()
    fireEvent.change(screen.getByLabelText('站点名称'), { target: { value: '保留草稿' } })
    mock.turnstile.mockRejectedValueOnce(new Error('验证配置读取失败'))
    await userEvent.click(screen.getByRole('tab', { name: '安全验证' }))
    await screen.findByRole('alert')
    await userEvent.click(screen.getByRole('tab', { name: 'Passkey' }))
    await screen.findByLabelText('Passkey 显示名称')
    await userEvent.click(screen.getByRole('tab', { name: '安全验证' }))
    await userEvent.click(screen.getByRole('button', { name: '重试' }))
    await screen.findByLabelText('Site Key')
    await userEvent.click(screen.getByRole('tab', { name: '站点信息' }))
    expect(screen.getByLabelText('站点名称')).toHaveValue('保留草稿')
    expect(mock.branding).toHaveBeenCalledTimes(1)
  })
  it('修改验证配置后清除旧测试结果，配置齐全不等同于测试通过', async () => {
    mock.testTurnstile.mockResolvedValue({ ok: true, message: '本次服务端测试通过' })
    await show(true)
    expect(screen.getByText(/实际可用性请通过右侧验证测试确认/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '开始 / 重新验证' }))
    fireEvent.click(screen.getByRole('button', { name: '完成小组件' }))
    fireEvent.click(screen.getByRole('button', { name: '检查服务端验证' }))
    await screen.findByText('本次服务端测试通过')
    fireEvent.change(screen.getByLabelText('Site Key'), { target: { value: 'new-site-key' } })
    expect(screen.queryByText('本次服务端测试通过')).not.toBeInTheDocument()
    expect(screen.getByText('尚未完成验证测试。')).toBeInTheDocument()
  })
  it('恢复焦点不重新选择旧页面，键盘 Enter 才激活页签', async () => {
    await show(true)
    const branding = screen.getByRole('tab', { name: '站点信息' })
    branding.focus()
    expect(screen.getByRole('tab', { name: '安全验证' })).toHaveAttribute('aria-selected', 'true')
    await userEvent.keyboard('{Enter}')
    await screen.findByLabelText('站点名称')
    expect(branding).toHaveAttribute('aria-selected', 'true')
  })
})
