import { createHash } from 'node:crypto'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

// Keep the native app's bundled engine identical to the existing Web engine.
// Xcode consumes the checked-in resource and does not need Node or a network fetch.
const sourceURL = new URL('../../web/src/lib/edge.ts', import.meta.url)
const adapterURL = new URL('./reader-edge-adapter.js', import.meta.url)
const outputURL = new URL('../ZhiZhou/Resources/ReaderEdgeRuntime.js', import.meta.url)
const source = (await readFile(sourceURL, 'utf8')).replace(/\r\n/g, '\n')
const adapter = (await readFile(adapterURL, 'utf8')).replace(/\r\n/g, '\n')
const digest = createHash('sha256').update(source).update(adapter).digest('hex')
const compiled = ts.transpileModule(source, {
  compilerOptions: {
    target: ts.ScriptTarget.ES2020,
    module: ts.ModuleKind.CommonJS,
    removeComments: true,
    newLine: ts.NewLineKind.LineFeed,
  },
  reportDiagnostics: true,
})
const errors = compiled.diagnostics?.filter((entry) => entry.category === ts.DiagnosticCategory.Error) ?? []
if (errors.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(errors, {
  getCanonicalFileName: (name) => name,
  getCurrentDirectory: () => fileURLToPath(new URL('../../', import.meta.url)),
  getNewLine: () => '\n',
}))

const body = `var ReaderEdgeBridge = (function () {\nconst exports = {};\n${compiled.outputText}\n${adapter}\nreturn nativeBridge;\n})();\n`
const runtimeDigest = createHash('sha256').update(body).digest('hex')
const output = `// Generated by ios/scripts/sync-reader-edge.mjs. Do not edit.\n// Source SHA-256: ${digest}\n// Runtime SHA-256: ${runtimeDigest}\n${body}`
if (process.argv.includes('--check')) {
  const current = (await readFile(outputURL, 'utf8')).replace(/\r\n/g, '\n')
  if (current !== output) throw new Error('iOS 节拍规则资源已过期，请运行 node ios/scripts/sync-reader-edge.mjs')
  console.log('iOS 节拍规则资源与 Web 源码一致。')
} else {
  await mkdir(new URL('../ZhiZhou/Resources/', import.meta.url), { recursive: true })
  await writeFile(outputURL, output)
  console.log('已同步 iOS 节拍规则资源。')
}
